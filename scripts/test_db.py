"""Run with python -m scripts.test_db --help from the repository root."""

import argparse
import os
import subprocess
import sys

from scripts.test_database_support import (
    ROOT,
    TestDatabaseConfig,
    command_lock,
    guarded_connection,
    load_test_config,
)


def compose(config: TestDatabaseConfig, *args: str) -> int:
    return subprocess.call(
        [
            "docker",
            "compose",
            "--env-file",
            str(ROOT / ".env.test"),
            "-p",
            "quickapi-fastapi-test",
            "-f",
            str(ROOT / "docker-compose.test.yml"),
            *args,
        ],
        cwd=ROOT,
        env={**os.environ, **config.values},
    )


def command_environment(config: TestDatabaseConfig) -> dict[str, str]:
    return {
        **os.environ,
        **config.values,
        "APP_NAME": "QuickAPI Tests",
        "APP_VERSION": "1.3.0",
        "PORT": "8000",
        "LOG_LEVEL": "ERROR",
        "DATABASE_URL": config.url.render_as_string(hide_password=False),
        "QUICKAPI_TEST_RUN": "true",
    }


async def migration(
    config: TestDatabaseConfig, action: str, revision: str, message: str = ""
) -> None:
    os.environ.update(command_environment(config))
    from alembic import command

    from app.config.database_transport import build_database_engine
    from app.config.migrations import migration_config

    engine = build_database_engine(config.url)

    try:
        async with guarded_connection(engine, config) as connection:

            def apply(sync_connection: object) -> None:
                cfg = migration_config()
                cfg.attributes["connection"] = sync_connection

                if action == "migrate":
                    command.upgrade(cfg, "head")
                elif action == "downgrade":
                    command.downgrade(cfg, revision)
                elif action == "current":
                    command.current(cfg)
                elif action == "check":
                    command.check(cfg)
                elif action == "history":
                    command.history(cfg)
                elif action == "heads":
                    command.heads(cfg)
                elif action == "revision":
                    command.revision(cfg, message=message, autogenerate=True)

            await connection.run_sync(apply)
            await connection.commit()
    finally:
        await engine.dispose()


def run_migration(
    config: TestDatabaseConfig, action: str, revision: str, message: str = ""
) -> None:
    os.environ.update(command_environment(config))
    from app.config.event_loop import run_database

    run_database(migration(config, action, revision, message))


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Guarded disposable MySQL tests and migrations; never loads .env."
    )

    parser.add_argument(
        "action",
        choices=[
            "up",
            "down",
            "logs",
            "migrate",
            "current",
            "check",
            "history",
            "heads",
            "revision",
            "downgrade",
            "test",
            "tls",
        ],
    )
    parser.add_argument("--layer", choices=["integration", "e2e", "all"], default="all")
    parser.add_argument(
        "--message", help="Description for a proposed autogenerated revision."
    )
    parser.add_argument(
        "--revision",
        default="-1",
        help="Downgrade target; default undoes the latest revision.",
    )
    parser.add_argument(
        "--keep-db",
        action="store_true",
        help="Retain disposable infrastructure after a test run for inspection.",
    )
    args = parser.parse_args()

    if args.action == "revision" and not args.message:
        parser.error("revision requires --message")

    config = load_test_config()

    if args.action == "logs":
        return compose(config, "logs", "--no-color", "--tail", "100", "mysql-test")

    with command_lock():
        return dispatch(config, args)


def dispatch(config: TestDatabaseConfig, args: argparse.Namespace) -> int:
    if args.action == "tls":
        from scripts.test_database_tls import run_tls

        return run_tls(config)

    if args.action == "up":
        return compose(config, "up", "-d", "--wait", "mysql-test")

    if args.action == "down":
        return compose(config, "down", "--volumes")

    if args.action != "test":
        run_migration(config, args.action, args.revision, args.message or "")

        return 0

    result = 1

    try:
        result = compose(config, "up", "-d", "--wait", "mysql-test")

        if result:
            return result

        result = 1

        run_migration(config, "migrate", "head")
        selection: str = (
            "unit or integration or e2e" if args.layer == "all" else args.layer
        )
        command: list[str] = [
            sys.executable,
            "-m",
            "pytest",
            "-m",
            selection,
        ]

        if args.layer != "all":
            command.append("--no-cov")

        collected = subprocess.run(
            [*command, "--collect-only", "--no-cov", "-q"],
            cwd=ROOT,
            env=command_environment(config),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        result = collected.returncode

        if result:
            print(collected.stdout)

        if result == 0:
            result = subprocess.call(
                [*command, "-q"], cwd=ROOT, env=command_environment(config)
            )

        return result
    finally:
        if result:
            compose(config, "logs", "--no-color", "--tail", "100", "mysql-test")

        if not args.keep_db:
            cleanup = compose(config, "down", "--volumes")

            if cleanup and result == 0:
                raise RuntimeError("Disposable MySQL cleanup failed.")


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
    except Exception:
        # Driver errors can include SQL, connection details, or credentials.
        print(
            "Disposable database command failed. Verify .env.test, target safety, database health, and migration state.",
            file=sys.stderr,
        )
        sys.exit(1)
