import shutil
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import AsyncEngine

from app.common.handlers.lifecycle_handler import LifecycleHandler
from app.config import database, migrations

pytestmark = pytest.mark.integration
FIXTURES = Path(__file__).resolve().parents[2] / "fixtures" / "migrations"


def evidence_config(path: Path, revision: str) -> Config:
    versions = path / "versions"
    versions.mkdir(parents=True)
    shutil.copyfile(FIXTURES / "env.py", path / "env.py")
    for name in ["base", revision]:
        shutil.copyfile(FIXTURES / f"{name}.py", versions / f"{name}.py")
    config = Config()
    config.set_main_option("script_location", str(path))
    return config


async def apply(
    engine: AsyncEngine, config: Config, target: str, *, downgrade: bool = False
) -> None:
    async with engine.connect() as connection:

        def run(conn: Connection) -> None:
            config.attributes["connection"] = conn
            if downgrade:
                command.downgrade(config, target)
            else:
                command.upgrade(config, target)

        await connection.run_sync(run)
        await connection.commit()


async def cleanup(engine: AsyncEngine) -> None:
    async with engine.begin() as connection:
        await connection.execute(
            text("DROP TABLE IF EXISTS migration_evidence_partial")
        )
        await connection.execute(
            text("DROP TABLE IF EXISTS migration_evidence_version")
        )


async def test_real_baseline_downgrade_is_destructive_and_fresh_upgrade_matches_models(
    database_engine: AsyncEngine,
) -> None:
    from alembic.autogenerate import compare_metadata
    from alembic.migration import MigrationContext

    config = migrations.migration_config()
    try:
        async with database_engine.begin() as connection:
            await connection.execute(
                text(
                    "INSERT INTO items (id,name,price) VALUES ('discarded','Disposable',1)"
                )
            )
        await apply(database_engine, config, "base", downgrade=True)
        async with database_engine.connect() as connection:
            assert "items" not in await connection.run_sync(
                lambda conn: inspect(conn).get_table_names()
            )
    finally:
        await apply(database_engine, config, "head")
    async with database_engine.connect() as connection:
        assert (
            await connection.execute(text("SELECT COUNT(*) FROM items"))
        ).scalar_one() == 0
        assert (
            await connection.run_sync(
                lambda conn: compare_metadata(
                    MigrationContext.configure(conn), database.Base.metadata
                )
            )
            == []
        )


async def test_data_bearing_upgrade_downgrade_and_reapply(
    database_engine: AsyncEngine, tmp_path: Path
) -> None:
    config = evidence_config(tmp_path / "chain", "backfill")
    async with database_engine.begin() as connection:
        await connection.execute(
            text(
                "INSERT INTO items (id,name,price,description) VALUES ('one','Café',12.34,NULL),('two','Zero',0,'existing description')"
            )
        )
        before = (
            await connection.execute(
                text(
                    "SELECT id,name,price,description,createdAt,updatedAt FROM items ORDER BY id"
                )
            )
        ).all()
    upgraded = False
    try:
        await apply(database_engine, config, "head")
        upgraded = True
        async with database_engine.begin() as connection:
            assert (
                await connection.execute(
                    text(
                        "SELECT id,name,price,description,createdAt,updatedAt FROM items ORDER BY id"
                    )
                )
            ).all() == before
            assert (
                await connection.execute(
                    text("SELECT evidence_label FROM items ORDER BY id")
                )
            ).scalars().all() == ["Café", "Zero"]

            def schema(conn: Connection) -> None:
                assert any(
                    index["name"] == "ix_items_evidence_label"
                    for index in inspect(conn).get_indexes("items")
                )
                column = next(
                    c
                    for c in inspect(conn).get_columns("items")
                    if c["name"] == "evidence_label"
                )
                assert column["nullable"] is False and column["default"] is not None

            await connection.run_sync(schema)
            await connection.execute(
                text("INSERT INTO items (id,name,price) VALUES ('new','New',1)")
            )
            assert (
                await connection.execute(
                    text("SELECT evidence_label FROM items WHERE id='new'")
                )
            ).scalar_one() == "new"
        await apply(database_engine, config, "evidence_base", downgrade=True)
        upgraded = False
        async with database_engine.connect() as connection:
            assert (
                await connection.execute(
                    text(
                        "SELECT id,name,price,description,createdAt,updatedAt FROM items WHERE id <> 'new' ORDER BY id"
                    )
                )
            ).all() == before
            assert "evidence_label" not in await connection.run_sync(
                lambda conn: [c["name"] for c in inspect(conn).get_columns("items")]
            )
        await apply(database_engine, config, "head")
        upgraded = True
    finally:
        if upgraded:
            await apply(database_engine, config, "evidence_base", downgrade=True)
        await cleanup(database_engine)


async def test_failed_ddl_leaves_history_unadvanced_and_requires_explicit_cleanup(
    database_engine: AsyncEngine, tmp_path: Path
) -> None:
    config = evidence_config(tmp_path / "failure", "failure")
    try:
        await apply(database_engine, config, "evidence_base")
        with pytest.raises(RuntimeError, match="Deliberate migration failure"):
            await apply(database_engine, config, "head")
        async with database_engine.connect() as connection:
            assert (
                await connection.execute(
                    text("SELECT version_num FROM migration_evidence_version")
                )
            ).scalar_one() == "evidence_base"
            tables = await connection.run_sync(
                lambda conn: inspect(conn).get_table_names()
            )
            if database_engine.dialect.name == "mysql":
                assert "migration_evidence_partial" in tables
            await connection.run_sync(migrations.check_revision)
    finally:
        await cleanup(database_engine)


@pytest.mark.parametrize("damage", ["missing_index", "extra_column"])
async def test_revision_match_does_not_hide_schema_drift(
    database_engine: AsyncEngine, damage: str
) -> None:
    async with database_engine.connect() as connection:
        await connection.run_sync(migrations.check_revision)

        def check(conn: Connection) -> None:
            config = migrations.migration_config()
            config.attributes["connection"] = conn
            command.check(config)

        await connection.run_sync(check)
        try:
            if damage == "missing_index":
                await connection.run_sync(
                    lambda conn: next(
                        i
                        for i in database.Base.metadata.tables["items"].indexes
                        if i.name == "ix_items_name"
                    ).drop(conn)
                )
            else:
                await connection.execute(
                    text("ALTER TABLE items ADD COLUMN evidence_drift INTEGER")
                )
            await connection.commit()
            await connection.run_sync(migrations.check_revision)
            with pytest.raises(AutogenerateDiffsDetected):
                await connection.run_sync(check)
        finally:
            if damage == "missing_index":
                await connection.run_sync(
                    lambda conn: next(
                        i
                        for i in database.Base.metadata.tables["items"].indexes
                        if i.name == "ix_items_name"
                    ).create(conn)
                )
            else:
                await connection.execute(
                    text("ALTER TABLE items DROP COLUMN evidence_drift")
                )
            await connection.commit()
        await connection.run_sync(check)


@pytest.mark.parametrize(
    "revision", ["older_revision", "newer_revision", "unknown_revision"]
)
async def test_application_rejects_incompatible_history_before_readiness(
    database_engine: AsyncEngine, revision: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(database, "engine", database_engine)
    lifecycle = LifecycleHandler()
    lifecycle.register([database.DatabaseService()])
    try:
        async with database_engine.begin() as connection:
            await connection.execute(
                text("UPDATE alembic_version SET version_num=:revision"),
                {"revision": revision},
            )
        with pytest.raises(RuntimeError, match="schema revision is not current"):
            await lifecycle.startup()
        assert lifecycle.is_ready() is False
    finally:
        async with database_engine.begin() as connection:
            await connection.execute(
                text("UPDATE alembic_version SET version_num='0001_create_items'")
            )
    await lifecycle.startup()
    assert lifecycle.is_ready() is True
    await lifecycle.shutdown()


async def test_multiple_source_heads_rejected(
    database_engine: AsyncEngine, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    config = evidence_config(tmp_path / "branches", "backfill")
    (tmp_path / "branches" / "versions" / "branch.py").write_text(
        "revision='another_head'\ndown_revision='evidence_base'\n"
    )
    assert len(ScriptDirectory.from_config(config).get_heads()) == 2
    monkeypatch.setattr(migrations, "migration_config", lambda: config)
    async with database_engine.connect() as connection:
        with pytest.raises(RuntimeError, match="schema revision is not current"):
            await connection.run_sync(migrations.check_revision)
